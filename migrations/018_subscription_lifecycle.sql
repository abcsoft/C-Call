-- migrations/018_subscription_lifecycle.sql
-- Subscription lifecycle enforcement: subscriptions, events, payments tables;
-- trial/grace/expiry columns on tenants; billing_cycle on plans.
-- Safe to run multiple times (IF NOT EXISTS / DO $$ guards everywhere).

BEGIN;

-- ── 1. plans: add trial_days and price_yearly ─────────────────────────────
ALTER TABLE plans ADD COLUMN IF NOT EXISTS trial_days INT NOT NULL DEFAULT 14;
ALTER TABLE plans ADD COLUMN IF NOT EXISTS price_yearly NUMERIC(10,2);

-- ── 2. tenants: add trial tracking columns ────────────────────────────────
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS trial_started_at TIMESTAMPTZ;
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS trial_ends_at TIMESTAMPTZ;

-- ── 3. tenants.status CHECK: extend to include grace_period, past_due, expired ──
DO $$
BEGIN
    -- Drop old constraint (name generated by Postgres from the DEFAULT clause)
    IF EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'tenants_status_check'
          AND conrelid = 'tenants'::regclass
    ) THEN
        ALTER TABLE tenants DROP CONSTRAINT tenants_status_check;
    END IF;
END $$;

ALTER TABLE tenants
    ADD CONSTRAINT tenants_status_check
    CHECK (status IN ('active','suspended','trial','cancelled','grace_period','past_due','expired'));

-- ── 4. subscriptions table ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS subscriptions (
    id                  SERIAL PRIMARY KEY,
    tenant_id           INT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    plan_id             INT NOT NULL REFERENCES plans(id),
    billing_cycle       TEXT NOT NULL DEFAULT 'monthly' CHECK (billing_cycle IN ('monthly','yearly')),
    status              TEXT NOT NULL DEFAULT 'trialing'
                        CHECK (status IN ('trialing','active','grace_period','past_due','cancelled','expired')),
    started_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    current_period_start TIMESTAMPTZ,
    current_period_end   TIMESTAMPTZ,
    grace_ends_at       TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    cancellation_reason TEXT,
    renewal_count       INT NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_tenant
    ON subscriptions (tenant_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status
    ON subscriptions (status)
    WHERE status IN ('trialing','active','grace_period','past_due');

-- ── 5. current_subscription_id FK on tenants ──────────────────────────────
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS current_subscription_id INT
    REFERENCES subscriptions(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_tenants_current_sub
    ON tenants (current_subscription_id)
    WHERE current_subscription_id IS NOT NULL;

-- ── 6. subscription_events table ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS subscription_events (
    id              BIGSERIAL PRIMARY KEY,
    subscription_id INT REFERENCES subscriptions(id) ON DELETE SET NULL,
    tenant_id       INT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    event_type      TEXT NOT NULL,   -- trial_started, activated, grace_period_started, past_due,
                                     -- expired, cancelled, renewed, admin_extended, reactivated
    from_status     TEXT,
    to_status       TEXT,
    actor_type      TEXT DEFAULT 'system',  -- system | admin | customer
    actor_id        INT,                    -- user_id for admin/customer actor
    reason          TEXT,
    metadata        JSONB DEFAULT '{}',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sub_events_tenant
    ON subscription_events (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sub_events_sub
    ON subscription_events (subscription_id, created_at DESC);

-- ── 7. subscription_payments table ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS subscription_payments (
    id                  SERIAL PRIMARY KEY,
    subscription_id     INT NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    tenant_id           INT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    payment_intent_id   INT REFERENCES payment_intents(id) ON DELETE SET NULL,
    amount              NUMERIC(14,4) NOT NULL,
    currency            TEXT NOT NULL DEFAULT 'BDT',
    billing_period_start TIMESTAMPTZ,
    billing_period_end   TIMESTAMPTZ,
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending','completed','failed','refunded')),
    idempotency_key     TEXT UNIQUE,   -- prevent duplicate charges per billing period
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sub_payments_subscription
    ON subscription_payments (subscription_id);
CREATE INDEX IF NOT EXISTS idx_sub_payments_tenant
    ON subscription_payments (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sub_payments_idempotency
    ON subscription_payments (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

-- ── 8. Backfill: stamp trial_started_at for existing trial tenants ────────
UPDATE tenants
SET trial_started_at = created_at
WHERE status = 'trial'
  AND trial_started_at IS NULL;

-- Default trial = 14 days from sign-up (plan.trial_days applied on first plan load)
UPDATE tenants t
SET trial_ends_at = t.created_at + INTERVAL '14 days'
FROM plans p
WHERE t.plan_id = p.id
  AND t.status = 'trial'
  AND t.trial_ends_at IS NULL;

-- For tenants with no plan assigned, use 14-day default
UPDATE tenants
SET trial_ends_at = created_at + INTERVAL '14 days'
WHERE status = 'trial'
  AND trial_ends_at IS NULL;

-- ── 9. Backfill: create initial subscription records for active tenants ───
INSERT INTO subscriptions (tenant_id, plan_id, billing_cycle, status, started_at,
                           current_period_start, current_period_end)
SELECT
    t.id,
    COALESCE(t.plan_id, (SELECT id FROM plans ORDER BY id LIMIT 1)),
    'monthly',
    'active',
    t.created_at,
    date_trunc('month', now()),
    date_trunc('month', now()) + INTERVAL '1 month'
FROM tenants t
WHERE t.status = 'active'
  AND NOT EXISTS (SELECT 1 FROM subscriptions s WHERE s.tenant_id = t.id)
ON CONFLICT DO NOTHING;

-- Link tenants to their subscription records
UPDATE tenants t
SET current_subscription_id = s.id
FROM subscriptions s
WHERE s.tenant_id = t.id
  AND t.current_subscription_id IS NULL
  AND t.status = 'active';

COMMIT;
